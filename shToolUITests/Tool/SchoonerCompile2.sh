func_kill_process_if_exist(){
	process_name=$1
	process_id=`ps -ef | grep $process_name | grep -v grep` 
	if [[ ${#process_id} != 0 ]]; then
		echo "[杀进程] ${process_name}"
		killall $process_name
	fi
}

func_backup_dir_if_exist(){
	dir_path=$1

	if [[ ! -e $dir_path ]]; then
		echo "[备  份] 文件不存在，跳过：$dir_path"
		return 0
	fi

	base_name=`basename $dir_path`
	dir_name=`dirname $dir_path`
	bakup_dir="${dir_name}/${base_name}_Backup"
	date_str=`date "+%Y%m%d%H%M%S"`
	target_dir="${bakup_dir}/${base_name}"

	echo "[备  份] 目录：$dir_path"
	if [[ ! -e $bakup_dir ]]; then
		echo "[创  建] 备份目录：$bakup_dir"
		mkdir $bakup_dir
	fi
	echo "[移  动] 目录：$dir_path -> $target_dir"
	mv $dir_path $target_dir
	echo "[切  换] 目录：${bakup_dir}"
	cd ${bakup_dir}
	echo "[压  缩] 目录：${base_name} -> ${base_name}_${date_str}.zip"
	zip -q -r "${base_name}_${date_str}.zip" ${base_name}
	# echo "[删  除] 目录：${base_name}"
	# rm -rf ${base_name}
	echo "[移  动] 目录：$target_dir -> $dir_path"
	mv $target_dir $dir_path
}

func_dir_exist(){
	dir=$1
	if [[ -e $dir ]]; then
		return 0
	else
		return 1
	fi
}

func_remove_file_if_exist(){
	file_path=$1
	if [[ -d $file_path ]]; then
		if [[ -e $file_path ]]; then
			echo "[删  除] 目录：$file_path"
			rm -rf $file_path
		fi
	else
		if [[ -e $file_path ]]; then
			echo "[删  除] 文件：$file_path"
			rm -f $file_path
		fi
	fi
	
}

func_fix_test_condition_error(){
	error_log=$1
	limits_table=$2
	
	# 检查是否包含 "Test Condition:xxxx is not generated by any test" 错误
	if echo "$error_log" | grep -q "Test Condition:.*is not generated by any test"; then
		echo -e '\033[;33;1m'
		echo "[检测] 发现测试条件错误，开始自动修复..."
		echo -e "\033[0m"
		
		# 提取所有测试条件名称（兼容 macOS 和 Linux）
		# 使用 sed 提取 "Details: Test Condition:xxxx is not generated by any test" 中的 xxxx
		test_conditions=$(echo "$error_log" | grep "Details: Test Condition:" | sed -n 's/.*Details: Test Condition:\([^ ]*\) is not generated by any test.*/\1/p')
		
		if [ -z "$test_conditions" ]; then
			echo "[警告] 无法提取测试条件名称"
			return 1
		fi
		
		# 备份 LimitsTable.csv
		backup_file="${limits_table}.backup_$(date +%Y%m%d_%H%M%S)"
		cp "$limits_table" "$backup_file"
		echo "[备份] 已备份 LimitsTable.csv 到: $backup_file"
		
		# 处理每个测试条件
		fixed_count=0
		while IFS= read -r test_condition; do
			if [ -z "$test_condition" ]; then
				continue
			fi
			
			echo "[修复] 处理测试条件: $test_condition"
			
			# 检查是否存在
			matching_lines=$(grep -c "$test_condition" "$limits_table" 2>/dev/null || echo "0")
			
			if [ "$matching_lines" -gt 0 ]; then
				# 删除包含该测试条件的行
				temp_file=$(mktemp)
				grep -v "$test_condition" "$limits_table" > "$temp_file"
				mv "$temp_file" "$limits_table"
				echo "[删除] 已删除 $matching_lines 行包含 '$test_condition' 的记录"
				fixed_count=$((fixed_count + 1))
			else
				echo "[信息] LimitsTable.csv 中未找到包含 '$test_condition' 的行"
			fi
		done <<< "$test_conditions"
		
		if [ $fixed_count -gt 0 ]; then
			echo -e '\033[;32;1m'
			echo "[完成] 已修复 $fixed_count 个测试条件错误"
			echo -e "\033[0m"
			return 0
		else
			echo "[信息] 未找到需要删除的行"
			return 1
		fi
	else
		return 1
	fi
}

THIS_FILE=`basename "$0"`

# 当前路径
SHELL_FOLDER=$(cd "$(dirname "$0")";pwd)
# Atlas2代码路径
ATLAS2_FOLDER="${HOME}/Library/Atlas2"
LIB_ATLAS2_FOLDER=${ATLAS2_FOLDER}

# 备份Atlas2
func_backup_dir_if_exist ${ATLAS2_FOLDER}


#生成Schooner Coverage
PATH_COMPILER="${LIB_ATLAS2_FOLDER}/Modules/Schooner/Compiler/BuildSchoonerSequence.lua"
PATH_TO_MAIN_CSV="${LIB_ATLAS2_FOLDER}/Assets/InputTables/MainTable.csv"
PATH_TO_LIMIT_CSV="${LIB_ATLAS2_FOLDER}/Assets/InputTables/LimitsTable.csv"
PATH_TO_CONDITION_CSV="${LIB_ATLAS2_FOLDER}/Assets/InputTables/ConditionTable.csv"
PATH_TO_TEST_DEF_FOLDER="${LIB_ATLAS2_FOLDER}/Assets/TestDefinitions"
OUTPUT_FILE="${LIB_ATLAS2_FOLDER}/Modules/coverage/coverage.lua"
STATION_PLIST="${LIB_ATLAS2_FOLDER}/Config/station.plist"
func_remove_file_if_exist ${OUTPUT_FILE}
mkdir -p "${LIB_ATLAS2_FOLDER}/Modules/coverage"
echo "[编  译] AtlasLua ${PATH_COMPILER} -m ${PATH_TO_MAIN_CSV} -l ${PATH_TO_LIMIT_CSV} -c ${PATH_TO_CONDITION_CSV} -t ${PATH_TO_TEST_DEF_FOLDER} -o ${OUTPUT_FILE} -p ${STATION_PLIST}"

log=""
max_retry=10
retry_count=0
compile_success=false

while [ $retry_count -lt $max_retry ] && [ "$compile_success" = false ]; do
	if [[ -f ${PATH_TO_CONDITION_CSV} ]]; then
		log=$(AtlasLua ${PATH_COMPILER} -m ${PATH_TO_MAIN_CSV} -l ${PATH_TO_LIMIT_CSV} -c ${PATH_TO_CONDITION_CSV} -t ${PATH_TO_TEST_DEF_FOLDER} -o ${OUTPUT_FILE} -p ${STATION_PLIST} 2>&1)
	else
		log=$(AtlasLua ${PATH_COMPILER} -m ${PATH_TO_MAIN_CSV} -l ${PATH_TO_LIMIT_CSV} -t ${PATH_TO_TEST_DEF_FOLDER} -o ${OUTPUT_FILE} -p ${STATION_PLIST} 2>&1)
	fi
	
	echo -e "build_Log: $log"
	
	# 检查编译是否成功（没有错误信息）
	if echo "$log" | grep -qi "Error:"; then
		# 检查是否是测试条件错误
		if func_fix_test_condition_error "$log" "$PATH_TO_LIMIT_CSV"; then
			retry_count=$((retry_count + 1))
			echo -e '\033[;33;1m'
			echo "[重试] 第 $retry_count 次重新编译..."
			echo -e "\033[0m"
			# 继续循环重试
		else
			# 其他错误，不重试
			compile_success=false
			break
		fi
	else
		# 编译成功
		compile_success=true
		if [ $retry_count -gt 0 ]; then
			echo -e '\033[;32;1m'
			echo "[成功] 编译成功（经过 $retry_count 次自动修复）"
			echo -e "\033[0m"
		fi
	fi
done

if [ "$compile_success" = false ]; then
	echo -e '\033[;31;1m'
	echo "[错误] 编译失败，请检查错误信息"
	echo -e "\033[0m"
fi

